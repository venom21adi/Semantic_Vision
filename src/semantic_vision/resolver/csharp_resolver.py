@functools.cache
def _bcl_members() -> dict[str, frozenset[str]]:
    """Public instance-method names per .NET framework type (simple name), generated by
    `scripts/csharp/bcl_members` and shipped as package data. Empty if it is missing, in
    which case the resolver simply loses the "the library already has this method" check."""
    try:
        resource = importlib.resources.files("semantic_vision.resolver").joinpath(
            "data/bcl_members.json.gz"
        )
        with resource.open("rb") as fh:
            raw = json.loads(gzip.decompress(fh.read()))
    except (OSError, ValueError, ModuleNotFoundError):
        return {}
    return {k: frozenset(v) for k, v in raw.items()}


_ALIASES = {"string": "String", "int": "Int32", "long": "Int64", "bool": "Boolean", "char": "Char"}


def _library_has_instance(type_name: str, method: str) -> bool:
    """Does the .NET library type `type_name` declare (or inherit) an instance method
    `method`? Instance methods always beat extension methods in C#."""
    base = "Array" if type_name.endswith("[]") else type_name
    base = _ALIASES.get(base, base)
    return method in _bcl_members().get(base, ())


