class TypeDecl:
    """One source declaration of a type (a partial type has several)."""

    __slots__ = (
        "rel_path", "class_id", "name", "qual", "namespace", "data", "raw", "outer", "methods",
        "nested", "scope", "base_scope", "key", "tkey",
    )  # fmt: skip

    def __init__(
        self,
        rel_path: str,
        class_id: str,
        raw: RawClass,
        namespace: str,
        outer: TypeDecl | None,
    ) -> None:
        self.rel_path = rel_path
        self.class_id = class_id
        self.name = raw.name.split("`")[0]  # display name; the graph id keeps any `n suffix
        self.raw = raw
        self.data: CsClassData = raw.lang_data
        self.namespace = namespace
        self.outer = outer
        self.tkey = tkey(self.name, len(self.data.own_type_params))
        self.qual = (
            f"{outer.qual}.{self.tkey}"
            if outer
            else (f"{namespace}.{self.tkey}" if namespace else self.tkey)
        )
        self.methods: dict[str, list[MethodDecl]] = defaultdict(list)
        self.nested: dict[str, TypeDecl] = {}
        self.scope: Scope | None = None
        self.base_scope: Scope | None = None
        """Where this type's base list is resolved: the *enclosing* scope (C# does not
        let a type's own members or inherited members participate), plus its type
        parameters. Using `scope` instead would recurse through inherited nested types."""
        self.key: tuple[str, ...] = ()  # identity of the *logical* type (partials share it)


class MethodDecl:
    __slots__ = ("node_id", "name", "data", "owner")

    def __init__(self, node_id: str, name: str, data: CsMethodData, owner: TypeDecl) -> None:
        self.node_id = node_id
        self.name = name
        self.data = data
        self.owner = owner


_SCOPE_IDS = itertools.count()


class Scope:
    """What a type name means at some point in the source. `uid` (not `id()`)
    keys the type-reference cache: scopes are created and dropped freely, and a
    recycled `id()` would silently return another scope's cached answer."""

    __slots__ = ("owner", "namespace", "usings", "type_params", "bounds", "uid")

    def __init__(
        self,
        owner: TypeDecl | None,
        namespace: str,
        usings: tuple[CsUsing, ...],
        type_params: frozenset[str],
        bounds: dict[str, tuple[str, ...]] | None = None,
    ) -> None:
        self.owner = owner
        self.namespace = namespace
        self.usings = usings
        self.type_params = type_params
        self.bounds = bounds or {}
        self.uid = next(_SCOPE_IDS)


@dataclass(frozen=True, slots=True)
class TRef:
    """A resolved type: internal (`decls` non-empty) or external (name only)."""

    name: str
    decls: tuple[TypeDecl, ...] = ()
    args: tuple[TRef | None, ...] = ()
    array_of: TRef | None = None
    nullable: bool = False
    """`T?` for a value type (`int?`, `DateTime?`): a distinct type from `T`."""
    static_ref: bool = False
    """The expression names the type itself (`Guid.Parse`), not a value of it:
    extension methods do not apply."""

    @property
    def internal(self) -> bool:
        return bool(self.decls)


def method_node_id(class_id: str, fn: RawFunction) -> str:
    """Mirrors `symbol_table._register_class`'s method id scheme exactly."""
    node_id = f"{class_id}.{fn.name}"
    if fn.accessor_kind is not None:
        node_id += f"#{fn.accessor_kind}"
    if fn.overload_index is not None:
        node_id += f"#{fn.overload_index}"
    return node_id


def tkey(name: str, arity: int) -> str:
    """CLR-style identity of a type name: `Identity` vs `Identity`1` (generic arity is
    part of a type's identity, so a repo may declare both)."""
    return f"{name}`{arity}" if arity else name


def _parent_namespace(ns: str) -> str:
    return ns.rpartition(".")[0]


class _ParsedType:
    __slots__ = ("name", "args", "array", "nullable")

    def __init__(
        self, name: str, args: tuple[str, ...], array: bool, nullable: bool = False
    ) -> None:
        self.name, self.args, self.array, self.nullable = name, args, array, nullable


