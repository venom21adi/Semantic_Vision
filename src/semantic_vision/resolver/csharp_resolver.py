"""Cross-file resolution for C#: a repository-wide type index, expression
typing, and call attribution.

The shared resolver (`resolver/calls.py`) matches dotted names against imports.
That is enough when a call spells out its target (`Util.format(x)`), but most C#
calls hang off a variable (`conn.Query<T>(...)`, `_cache.Get(key).Value.Trim()`),
and `using` imports a *namespace*, not a type. So this resolver works from type
evidence instead:

1. `CsIndex` is built once from every parsed file: all types by qualified and
   simple name, namespaces, per-type members and methods, extension methods.
2. A receiver expression is typed step by step (`type_of`): locals and
   parameters by declared type or by their initializer, fields and properties by
   declared type (searching base types), method calls by return type, `new`,
   casts, `await`, indexers, `foreach` elements.
3. The call is then looked up on the receiver's type (and its bases/interfaces),
   with overloads narrowed by argument count and extension methods considered.

Anything it cannot establish stays honest: a known library type becomes an
`external::Type.method` edge, a genuinely unknown receiver becomes
`unresolved::method`, and a candidate set that arity cannot narrow becomes
several `ambiguous` edges rather than a guess.
"""

