def _split_top_level(text: str) -> list[str]:
    parts, depth, cur = [], 0, []
    for ch in text:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    tail = "".join(cur).strip()
    if tail:
        parts.append(tail)
    return parts


def parse_type(text: str) -> _ParsedType:
    cached = _PARSE_CACHE.get(text)
    if cached is not None:
        return cached
    t = text.strip()
    for prefix in ("ref ", "in ", "out ", "readonly ", "scoped "):
        if t.startswith(prefix):
            t = t[len(prefix) :].strip()
    if t.startswith("global::"):
        t = t[len("global::") :]
    array = False
    nullable = False
    while t.endswith("?"):
        t = t[:-1]
        nullable = True
    while t.endswith("]"):
        depth = 0
        for i in range(len(t) - 1, -1, -1):
            if t[i] == "]":
                depth += 1
            elif t[i] == "[":
                depth -= 1
                if depth == 0:
                    t = t[:i]
                    array = True
                    break
        else:
            break
    while t.endswith("?"):
        t = t[:-1]
        nullable = True
    if t.startswith("("):
        parsed = _ParsedType("(tuple)", (), array, nullable)
    else:
        lt = t.find("<")
        if lt != -1 and t.endswith(">"):
            parsed = _ParsedType(
                t[:lt].strip(), tuple(_split_top_level(t[lt + 1 : -1])), array, nullable
            )
        else:
            parsed = _ParsedType(t, (), array, nullable)
    if len(_PARSE_CACHE) < 200_000:
        _PARSE_CACHE[text] = parsed
    return parsed


class CsIndex:
    """Repository-wide facts, built once after every file is parsed."""

    def __init__(self, modules: dict[str, RawModule], projects: ProjectMap | None = None) -> None:
        self.projects = projects
        """Project layout (`resolver/csharp_projects.py`); None when the repo has no
        `.csproj` files, in which case resolution falls back to path proximity."""
        self.by_qual: dict[str, list[TypeDecl]] = defaultdict(list)
        self.by_simple: dict[str, list[TypeDecl]] = defaultdict(list)
        self.by_simple_any: dict[str, list[TypeDecl]] = defaultdict(list)
        self.ns_types: dict[str, dict[str, list[TypeDecl]]] = defaultdict(lambda: defaultdict(list))
        self.namespaces: set[str] = set()
        self.ns_files: dict[str, Counter[str]] = defaultdict(Counter)
        self.extensions: dict[str, list[MethodDecl]] = defaultdict(list)
        self._global_usings: list[tuple[str, CsUsing]] = []
        self._global_cache: dict[str | None, tuple[CsUsing, ...]] = {}
        self.decl_by_class_id: dict[str, TypeDecl] = {}
        self._ref_cache: dict[tuple[int, str], TRef | None] = {}
        self._scope_cache: dict[tuple[int, frozenset[str]], Scope] = {}
        self._ext_base_cache: dict[tuple[int, ...], bool] = {}
        self._ext_names_cache: dict[tuple[int, ...], list[str]] = {}
        self._method_cache: dict[
            tuple[tuple[int, ...], str], tuple[list[tuple[int, MethodDecl]], bool]
        ] = {}
        self._members_cache: dict[tuple[tuple[int, ...], str], tuple[str, Scope] | None] = {}
        for rel_path, raw in modules.items():
            mdata: CsModuleData | None = raw.lang_data
            if mdata is not None:
                self._global_usings.extend((rel_path, u) for u in mdata.global_usings)
            for cls in raw.classes:
                self._add_type(rel_path, f"{rel_path}::{cls.name}", cls, None)
        for decl in list(self.decl_by_class_id.values()):
            decl.scope = Scope(
                decl, decl.namespace, decl.data.usings, decl.data.type_params, decl.data.constraints
            )
            decl.base_scope = Scope(
                decl.outer,
                decl.namespace,
                decl.data.usings,
                decl.data.type_params,
                decl.data.constraints,
            )
            parts = decl.namespace.split(".") if decl.namespace else []
            for i in range(1, len(parts) + 1):
                self.namespaces.add(".".join(parts[:i]))
        self._partial_groups()

    def _add_type(
        self, rel_path: str, class_id: str, cls: RawClass, outer: TypeDecl | None
    ) -> None:
        data: CsClassData = cls.lang_data
        if data is None:
            return
        decl = TypeDecl(rel_path, class_id, cls, data.namespace, outer)
        self.decl_by_class_id[class_id] = decl
        self.by_qual[decl.qual].append(decl)
        self.by_simple[decl.tkey].append(decl)
        self.by_simple_any[decl.name].append(decl)
        if outer is None:
            self.ns_types[data.namespace][decl.tkey].append(decl)
            if data.namespace:
                self.ns_files[data.namespace][rel_path.rpartition("/")[0]] += 1
        else:
            outer.nested[decl.tkey] = decl
        for fn in cls.methods:
            md: CsMethodData = fn.lang_data
            if md is None:
                continue
            mdecl = MethodDecl(method_node_id(class_id, fn), fn.name, md, decl)
            if md.kind == "indexer":
                decl.methods["this[]"].append(mdecl)  # typed by `x[i]`, never called by name
                continue
            if md.kind == "property":
                continue  # `a.Count()` is not the property `Count`
            decl.methods[fn.name].append(mdecl)
            if md.is_extension:
                self.extensions[fn.name].append(mdecl)
        for nested in cls.nested_classes:
            self._add_type(rel_path, f"{class_id}.{nested.name}", nested, decl)

    def _partial_groups(self) -> None:
        """Partial declarations of one qualified name *in one project* form one logical type
        (a `partial` cannot span projects); non-partial duplicates (a `Program` in every
        sample project) stay separate."""
        for qual, decls in self.by_qual.items():
            for d in decls:
                if d.data.is_partial:
                    project = self.projects.project_of(d.rel_path) if self.projects else None
                    d.key = (qual, "partial", project or "")
                else:
                    d.key = (qual, d.class_id)

    # -- type references --------------------------------------------------

    def group_of(self, decl: TypeDecl) -> tuple[TypeDecl, ...]:
        return tuple(d for d in self.by_qual[decl.qual] if d.key == decl.key)

    def namespace_directory(self, namespace: str, from_path: str) -> str:
        """The directory that best stands for `namespace` as seen from `from_path`: among
        the directories declaring it, those in a project the file can see, then the one
        holding the most of its types."""
        counts = self.ns_files.get(namespace)
        if not counts:
            return ""
        if self.projects:
            project = self.projects.project_of(from_path)
            if project is not None:
                reach = self.projects.reachable(project)
                visible = Counter(
                    {d: n for d, n in counts.items() if self.projects.project_of(f"{d}/_") in reach}
                )
                counts = visible or counts
        return counts.most_common(1)[0][0]

    def global_usings_for(self, from_path: str) -> tuple[CsUsing, ...]:
        """`global using` directives that apply to `from_path`: a global using covers only
        the project that declares it (every file when the repo has no project files)."""
        project = self.projects.project_of(from_path) if self.projects else None
        cached = self._global_cache.get(project)
        if cached is None:
            cached = tuple(
                u
                for path, u in self._global_usings
                if project is None or not self.projects or self.projects.project_of(path) == project
            )
            self._global_cache[project] = cached
        return cached

    def _visible(self, candidates: list[TypeDecl], from_path: str) -> list[TypeDecl]:
        """Candidates declared in a project the referencing file's project can see (itself
        and its references). Falls back to all candidates when nothing is visible, e.g.
        for loose files outside any project."""
        if not self.projects:
            return candidates
        project = self.projects.project_of(from_path)
        if project is None:
            return candidates
        reach = self.projects.reachable(project)
        visible = [d for d in candidates if self.projects.project_of(d.rel_path) in reach]
        return visible or candidates

    def _pick(self, candidates: list[TypeDecl], from_path: str) -> tuple[TypeDecl, ...] | None:
        """One logical type out of same-named candidates: those visible to the file's
        project, then a unique group, else the one sharing the longest path prefix with
        the referencing file, else none."""
        candidates = self._visible(candidates, from_path)
        groups: dict[tuple[str, ...], list[TypeDecl]] = defaultdict(list)
        for d in candidates:
            groups[d.key].append(d)
        if len(groups) == 1:
            return tuple(next(iter(groups.values())))
        best, best_len, tie = None, -1, False
        for g in groups.values():
            n = _common_prefix_len(g[0].rel_path, from_path)
            if n > best_len:
                best, best_len, tie = g, n, False
            elif n == best_len:
                tie = True
        return None if tie or best is None else tuple(best)

    def lookup_simple(
        self, name: str, scope: Scope, from_path: str, arity: int = 0
    ) -> tuple[TypeDecl, ...] | None:
        key = tkey(name, arity)
        # 1. nested types of the enclosing types (and, via bases, inherited nested types)
        owner = scope.owner
        while owner is not None:
            if key in owner.nested:
                return self.group_of(owner.nested[key])
            inherited = self._inherited_nested(owner, key)
            if inherited is not None:
                return inherited
            owner = owner.outer
        # 2. the enclosing namespaces, innermost first (includes the global namespace)
        ns = scope.namespace
        while True:
            cands = self.ns_types.get(ns, {}).get(key)
            if cands:
                return self._pick(cands, from_path)
            if not ns:
                break
            ns = _parent_namespace(ns)
        # 3. using directives
        for u in (*scope.usings, *self.global_usings_for(from_path)):
            if u.kind == "alias":
                if u.alias == name:
                    return self.lookup_qualified(u.target, scope, from_path)
            elif u.kind == "namespace":
                cands = self.ns_types.get(u.target, {}).get(key)
                if cands:
                    return self._pick(cands, from_path)
            elif u.kind == "static":
                for t in self.by_qual.get(u.target, ()):
                    if key in t.nested:
                        return self.group_of(t.nested[key])
        # 4. a repository-unique simple name (types in namespaces we could not place)
        cands = self.by_simple.get(key) or (
            self.by_simple_any.get(name) if len(self.by_simple_any.get(name, ())) == 1 else None
        )
        if cands:
            return self._pick(cands, from_path)
        return None

    def _inherited_nested(self, owner: TypeDecl, name: str) -> tuple[TypeDecl, ...] | None:
        seen: set[tuple[str, ...]] = {owner.key}
        stack = [owner]
        while stack:
            cur = stack.pop()
            for base_text in cur.data.bases:
                bref = self.resolve_type(base_text, cur.base_scope, cur.rel_path)
                if bref is None or not bref.internal:
                    continue
                for d in bref.decls:
                    if d.key in seen:
                        continue
                    seen.add(d.key)
                    if name in d.nested:
                        return self.group_of(d.nested[name])
                    stack.append(d)
        return None

    def lookup_qualified(
        self, dotted: str, scope: Scope, from_path: str, arity: int = 0
    ) -> tuple[TypeDecl, ...] | None:
        """`A.B.C` where C is a type: tried relative to each enclosing namespace,
        then as written, then by resolving the first segment as a type/alias."""
        init, _, last = dotted.rpartition(".")
        dotted = f"{init}.{tkey(last, arity)}" if init else tkey(last, arity)
        ns = scope.namespace
        while True:
            full = f"{ns}.{dotted}" if ns else dotted
            cands = self.by_qual.get(full)
            if cands:
                return self._pick(cands, from_path)
            if not ns:
                break
            ns = _parent_namespace(ns)
        head, _, rest = dotted.partition(".")
        if rest:
            for u in scope.usings:
                if u.kind == "alias" and u.alias == head:
                    return self.lookup_qualified(f"{u.target}.{rest}", scope, from_path)
            first = self.lookup_simple(head, scope, from_path) or self.lookup_simple(
                head, scope, from_path, 1
            )
            if first is not None:
                cur = first[0]
                for seg in rest.split("."):
                    nxt = cur.nested.get(seg) or next(
                        (n for k, n in cur.nested.items() if k.split("`")[0] == seg), None
                    )
                    if nxt is None:
                        return None
                    cur = nxt
                return self.group_of(cur)
        return None

    def resolve_type(self, text: str, scope: Scope | None, from_path: str) -> TRef | None:
        """`text` as a `TRef`: internal, external (named), or None for generic
        type parameters and unparseable forms."""
        if scope is None or not text:
            return None
        key = (scope.uid, text)
        if key in self._ref_cache:
            return self._ref_cache[key]
        parsed = parse_type(text)
        name = parsed.name
        result: TRef | None
        if name in ("var", "dynamic", ""):
            result = None
        elif name in scope.type_params and not parsed.args:
            result = self._bound_of(name, scope, from_path)
        elif name in _PREDEFINED:
            result = TRef(name=name)
        else:
            simple = name.rpartition(".")[2]
            if simple in scope.type_params and "." not in name:
                result = None
            else:
                arity = len(parsed.args)
                group = (
                    self.lookup_qualified(name, scope, from_path, arity)
                    if "." in name
                    else self.lookup_simple(name, scope, from_path, arity)
                )
                args = tuple(self.resolve_type(a, scope, from_path) for a in parsed.args)
                result = (
                    TRef(name=simple, decls=group, args=args)
                    if group
                    else TRef(name=simple, args=args)
                )
        if (
            parsed.nullable
            and not parsed.array
            and result is not None
            and (
                result.name in _VALUE_TYPES
                or (result.internal and result.decls[0].data.kind == "struct")
            )
        ):
            result = TRef(name=result.name, decls=result.decls, args=result.args, nullable=True)
        if parsed.array and result is not None:
            result = TRef(name=f"{result.name}[]", array_of=result)
        elif parsed.array:
            result = TRef(name="[]", array_of=None)
        self._ref_cache[key] = result
        return result

    def _bound_of(self, name: str, scope: Scope, from_path: str) -> TRef | None:
        """A generic parameter as its first class/interface constraint (`where T : Foo`),
        so `T x; x.Bar()` resolves through `Foo`. Unconstrained parameters stay unknown."""
        for text in scope.bounds.get(name, ()):
            base = parse_type(text).name
            if (
                base in ("class", "struct", "notnull", "unmanaged", "new()")
                or base in scope.type_params
            ):
                continue
            ref = self.resolve_type(base, scope, from_path)
            if ref is not None:
                return ref
        return None

    def method_scope(self, owner: TypeDecl | None, md: CsMethodData | None) -> Scope:
        """The owner's scope extended with the method's own generic parameters."""
        if owner is None or owner.scope is None:
            return Scope(
                None, "", (), md.type_params if md else frozenset(), md.constraints if md else None
            )
        extra = md.type_params if md is not None else frozenset()
        if not extra or extra <= owner.scope.type_params:
            return owner.scope
        key = (id(owner), extra)
        scope = self._scope_cache.get(key)
        if scope is None:
            scope = Scope(
                owner,
                owner.namespace,
                owner.data.usings,
                owner.scope.type_params | extra,
                {**owner.scope.bounds, **(md.constraints if md else {})},
            )
            self._scope_cache[key] = scope
        return scope

    def external_base_names(self, decls: tuple[TypeDecl, ...]) -> list[str]:
        """Simple names of the library types in the type's hierarchy (`Stream`, `Exception`)."""
        key = tuple(id(d) for d in decls)
        cached = self._ext_names_cache.get(key)
        if cached is None:
            cached = []
            hier, _ = self.hierarchy(decls)
            for _depth, d in hier:
                for base_text in d.data.bases:
                    ref = self.resolve_type(base_text, d.base_scope, d.rel_path)
                    if ref is not None and not ref.internal:
                        cached.append(ref.name)
            self._ext_names_cache[key] = cached
        return cached

    def has_external_base(self, decls: tuple[TypeDecl, ...]) -> bool:
        key = tuple(id(d) for d in decls)
        if key not in self._ext_base_cache:
            self._ext_base_cache[key] = self.hierarchy(decls)[1]
        return self._ext_base_cache[key]

    def resolve_type_subst(
        self, text: str, scope: Scope, from_path: str, subst: dict[str, TRef | None]
    ) -> TRef | None:
        """Like `resolve_type`, with some generic parameters bound (a call's explicit
        type arguments flowing into a generic method's return type)."""
        if not subst:
            return self.resolve_type(text, scope, from_path)
        parsed = parse_type(text)
        if parsed.name in subst and not parsed.args:
            bound = subst[parsed.name]
            return TRef(name=f"{bound.name}[]", array_of=bound) if parsed.array and bound else bound
        base = self.resolve_type(parsed.name, scope, from_path)
        if base is None:
            return None
        args = tuple(self.resolve_type_subst(a, scope, from_path, subst) for a in parsed.args)
        result = TRef(name=base.name, decls=base.decls, args=args, array_of=base.array_of)
        if parsed.array:
            return TRef(name=f"{result.name}[]", array_of=result)
        return result

    # -- hierarchy ----------------------------------------------------------

    def hierarchy(self, decls: tuple[TypeDecl, ...]) -> tuple[list[tuple[int, TypeDecl]], bool]:
        """Every declaration of the type and of its base types/interfaces, with
        depth, plus whether any base is external (so a missing member may simply
        be inherited from a library type)."""
        out: list[tuple[int, TypeDecl]] = []
        external_base = False
        seen: set[tuple[str, ...]] = set()
        frontier = [(0, decls)]
        while frontier:
            nxt: list[tuple[int, tuple[TypeDecl, ...]]] = []
            for depth, group in frontier:
                if not group or group[0].key in seen:
                    continue
                seen.add(group[0].key)
                for d in group:
                    out.append((depth, d))
                    for base_text in d.data.bases:
                        bref = self.resolve_type(base_text, d.base_scope, d.rel_path)
                        if bref is None:
                            continue
                        if bref.internal:
                            nxt.append((depth + 1, bref.decls))
                        else:
                            external_base = True
            frontier = nxt
        return out, external_base

    def methods_named(
        self, decls: tuple[TypeDecl, ...], name: str
    ) -> tuple[list[tuple[int, MethodDecl]], bool]:
        key = (tuple(id(d) for d in decls), name)
        cached = self._method_cache.get(key)
        if cached is not None:
            return cached
        hier, external_base = self.hierarchy(decls)
        found = [(depth, m) for depth, d in hier for m in d.methods.get(name, ())]
        self._method_cache[key] = (found, external_base)
        return found, external_base

    def member_type(self, decls: tuple[TypeDecl, ...], name: str) -> tuple[str, Scope] | None:
        key = (tuple(id(d) for d in decls), name)
        if key in self._members_cache:
            return self._members_cache[key]
        hier, _ = self.hierarchy(decls)
        result = None
        for _depth, d in hier:
            text = d.data.members.get(name)
            if text is not None and d.scope is not None:
                result = (text, d.scope)
                break
        self._members_cache[key] = result
        return result


def _common_prefix_len(a: str, b: str) -> int:
    n = 0
    for x, y in zip(a.split("/"), b.split("/"), strict=False):
        if x != y:
            break
        n += 1
    return n


