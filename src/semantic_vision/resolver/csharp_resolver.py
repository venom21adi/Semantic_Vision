class _Ctx:
    """Everything needed to type expressions inside one method body."""

    __slots__ = ("index", "owner", "scope", "md", "rel_path", "_in_progress")

    def __init__(
        self, index: CsIndex, owner: TypeDecl | None, md: CsMethodData | None, rel_path: str
    ) -> None:
        self.index = index
        self.owner = owner
        self.md = md
        self.rel_path = rel_path
        self.scope = index.method_scope(owner, md)
        self._in_progress: set[str] = set()

    def resolve(self, text: str) -> TRef | None:
        return self.index.resolve_type(text, self.scope, self.rel_path)

    def local_type(self, name: str) -> tuple[bool, TRef | None]:
        """(is_local, type). A name declared in the method shadows members even
        when its type is unknown."""
        if self.md is None or name not in self.md.locals:
            return False, None
        entry = self.md.locals[name]
        if entry.type_text is not None:
            return True, self.resolve(entry.type_text)
        if entry.init is not None and name not in self._in_progress:
            self._in_progress.add(name)
            try:
                return True, type_of(entry.init, self)
            finally:
                self._in_progress.discard(name)
        return True, None


def _element_of(t: TRef | None) -> TRef | None:
    if t is None:
        return None
    if t.array_of is not None:
        return t.array_of
    if t.name == "string":
        return TRef(name="char")
    if t.name in _COLLECTION_LIKE and len(t.args) == 1:
        return t.args[0]
    if t.name in _DICT_LIKE and len(t.args) == 2:
        return TRef(name="KeyValuePair", args=t.args)
    return None


def type_of(expr: CsExpr | None, ctx: _Ctx, depth: int = 0) -> TRef | None:
    if expr is None or depth > 8:
        return None
    k = expr.kind
    index = ctx.index
    if k == "this":
        if ctx.owner is None:
            return None
        return TRef(name=ctx.owner.name, decls=index.group_of(ctx.owner))
    if k == "base":
        if ctx.owner is None:
            return None
        for base_text in ctx.owner.data.bases:
            ref = index.resolve_type(base_text, ctx.owner.base_scope, ctx.owner.rel_path)
            if ref is None:
                continue
            if ref.internal and ref.decls[0].data.kind == "interface":
                continue
            if not ref.internal and _looks_like_interface(ref.name):
                continue
            return ref
        return None
    if k == "name":
        is_local, t = ctx.local_type(expr.name)
        if is_local:
            return t
        if ctx.owner is not None:
            group = index.group_of(ctx.owner)
            mt = index.member_type(group, expr.name)
            if mt is not None:
                return index.resolve_type(mt[0], mt[1], ctx.owner.rel_path)
            # An unknown capitalised name in a type with a library base class is most
            # likely an inherited member, not a static reference to a type.
            return _type_named(
                expr.name,
                ctx,
                allow_external=not index.has_external_base(group),
                arity=len(expr.type_args),
            )
        return _type_named(expr.name, ctx, allow_external=True, arity=len(expr.type_args))
    if k == "member":
        rt = type_of(expr.inner, ctx, depth + 1)
        if rt is not None and rt.internal:
            mt = index.member_type(rt.decls, expr.name)
            if mt is not None:
                return index.resolve_type(mt[0], mt[1], rt.decls[0].rel_path)
            nested = rt.decls[0].nested.get(tkey(expr.name, len(expr.type_args)))
            if nested is not None:
                return TRef(name=nested.name, decls=index.group_of(nested), static_ref=True)
            return None
        if rt is None or (not rt.internal and rt.static_ref):
            # `System.Console`: the head looked like a library type but is a namespace
            dotted = _pure_dotted(expr)
            if dotted is not None:
                return _type_named(dotted, ctx, allow_external=True, arity=len(expr.type_args))
        return None
    if k == "call":
        return _return_type(expr, ctx, depth)
    if k in ("new", "cast"):
        return ctx.resolve(expr.type_text)
    if k == "await":
        inner = type_of(expr.inner, ctx, depth + 1)
        if inner is not None and inner.name in _TASK_LIKE and len(inner.args) == 1:
            return inner.args[0]
        return None
    if k == "index":
        inner = type_of(expr.inner, ctx, depth + 1)
        if inner is None:
            return None
        if inner.internal:
            ms, _ = index.methods_named(inner.decls, "this[]")
            if ms:
                m = ms[0][1]
                rt = m.data.return_type
                return index.resolve_type(rt, m.owner.scope, m.owner.rel_path) if rt else None
            return None
        if inner.array_of is not None:
            return inner.array_of
        if inner.name in _COLLECTION_LIKE and len(inner.args) == 1:
            return inner.args[0]
        if inner.name in _DICT_LIKE and len(inner.args) == 2:
            return inner.args[1]
        return None
    if k == "elem":
        return _element_of(type_of(expr.inner, ctx, depth + 1))
    if k == "lambda_elem":
        # `items.Where(x => ...)`: `x` is the element type, for the LINQ-style methods
        # that pass elements to their first lambda parameter.
        if expr.name in _ELEMENT_LAMBDA_METHODS:
            return _element_of(type_of(expr.inner, ctx, depth + 1))
        return None
    if k == "literal":
        return TRef(name=expr.type_text)
    if k == "predef":
        return TRef(name=expr.type_text, static_ref=True)
    if k == "typeof":
        return TRef(name="Type")
    return None


def _pure_dotted(expr: CsExpr) -> str | None:
    parts: list[str] = []
    cur: CsExpr | None = expr
    while cur is not None:
        if cur.kind == "member":
            parts.append(cur.name)
            cur = cur.inner
        elif cur.kind == "name":
            parts.append(cur.name)
            return ".".join(reversed(parts))
        else:
            return None
    return None


def _looks_like_interface(name: str) -> bool:
    return len(name) > 1 and name[0] == "I" and name[1].isupper()


def _type_named(dotted: str, ctx: _Ctx, *, allow_external: bool, arity: int = 0) -> TRef | None:
    """A bare or qualified name used as an expression: a static reference to a type."""
    group = (
        ctx.index.lookup_qualified(dotted, ctx.scope, ctx.rel_path, arity)
        if "." in dotted
        else ctx.index.lookup_simple(dotted, ctx.scope, ctx.rel_path, arity)
    )
    if group:
        return TRef(name=dotted.rpartition(".")[2], decls=group, static_ref=True)
    # A library static reference (Math, Console, Path, System.IO.File ...) is just a name.
    last = dotted.rpartition(".")[2]
    first = dotted.split(".")[0]
    if first[:1].isupper() and (allow_external or first in _WELL_KNOWN_TYPES):
        return TRef(name=last, static_ref=True)
    return None


@dataclass(slots=True)
class Resolved:
    kind: str  # internal | external | unresolved | skip
    targets: list[str]
    ambiguous: bool = False
    display: str = ""


_SKIP = Resolved("skip", [])

_WIDENING: dict[str, frozenset[str]] = {
    "sbyte": frozenset({"short", "int", "long", "float", "double", "decimal"}),
    "byte": frozenset(
        {"short", "ushort", "int", "uint", "long", "ulong", "float", "double", "decimal"}
    ),
    "short": frozenset({"int", "long", "float", "double", "decimal"}),
    "ushort": frozenset({"int", "uint", "long", "ulong", "float", "double", "decimal"}),
    "int": frozenset({"long", "float", "double", "decimal"}),
    "uint": frozenset({"long", "ulong", "float", "double", "decimal"}),
    "long": frozenset({"float", "double", "decimal"}),
    "ulong": frozenset({"float", "double", "decimal"}),
    "char": frozenset({"ushort", "int", "uint", "long", "ulong", "float", "double", "decimal"}),
    "float": frozenset({"double"}),
}
_INTEGRAL = frozenset({"sbyte", "byte", "short", "ushort", "int", "uint", "long", "ulong", "char"})
_PRIMS = frozenset(_WIDENING) | {"double", "decimal", "bool", "string"}


def _arity_ok(md: CsMethodData, n: int, *, as_extension: bool = False) -> bool:
    n_params = n + 1 if as_extension else n
    hi = md.max_arity
    return md.min_arity <= n_params and (hi is None or n_params <= hi)


def _generic_ok(m: MethodDecl, call: CsCall) -> bool:
    return not call.type_args or m.data.generic_arity == len(call.type_args)


def _compat(arg: TRef | None, param: TRef | None, arg_expr: CsExpr, ctx: _Ctx) -> tuple[bool, int]:
    """Could `arg` be passed for `param`? Returns (possible, closeness score).
    Only drops a candidate when the mismatch is evident: the argument's type is
    certain (internal, primitive or literal) and clearly cannot convert."""
    if arg is None or param is None:
        return True, 0
    pn, an = param.name, arg.name
    if arg.array_of is not None or param.array_of is not None:
        if arg.array_of is not None and param.array_of is not None:
            return _compat(arg.array_of, param.array_of, UNKNOWN_EXPR, ctx)
        if pn in _OBJECT_LIKE or (
            param.array_of is None and not param.internal and pn not in _PRIMS
        ):
            return True, 0
        return False, 0
    if an == "null":
        return pn not in _PRIMS, 0
    if an == pn:
        if arg.nullable and not param.nullable:
            return False, 0  # `int?` cannot be passed for `int`
        return True, 2 if arg.nullable == param.nullable else 1
    if pn in _OBJECT_LIKE:
        return True, 0
    if an in _PRIMS and pn in _PRIMS:
        if arg.nullable and not param.nullable:
            return False, 0
        if pn in _WIDENING.get(an, ()):
            return True, 1
        if (
            arg_expr.kind == "literal"
            and an == "int"
            and pn in _INTEGRAL | {"double", "float", "decimal"}
        ):
            return True, 0
        return False, 0
    if arg.internal:
        if param.internal:
            hier, _ = ctx.index.hierarchy(arg.decls)
            if any(d.key == param.decls[0].key for _, d in hier):
                return True, 1
            return False, 0
        if pn in _PRIMS:
            return False, 0
        return True, 0
    if an in _PRIMS and param.internal:
        return False, 0
    if an in _PRIMS and (pn in _COLLECTION_LIKE or pn in _DICT_LIKE):
        # A primitive is never a collection; the one exception is `string`, which is
        # an `IEnumerable<char>` and converts to `ReadOnlySpan<char>`.
        return an == "string" and pn in ("IEnumerable", "ReadOnlySpan"), 0
    return True, 0


UNKNOWN_EXPR = CsExpr("unknown")


def _select(
    found: list[tuple[int, MethodDecl]],
    call: CsCall,
    ctx: _Ctx,
    *,
    skip_first_param: bool = False,
) -> list[MethodDecl]:
    """Overload candidates for a call, as C# resolves them: arity/generic-arity
    compatible, then (when the arguments' types are known) those whose parameters
    accept the arguments, *across the whole hierarchy*, then the nearest in the
    hierarchy and, among those, the closest parameter-type match. A derived class
    only hides a base method when its own overload is applicable."""
    arity = call.arity
    fits = [
        (d, m)
        for d, m in found
        if _arity_ok(m.data, arity, as_extension=skip_first_param) and _generic_ok(m, call)
    ]
    if not fits:
        return []
    seen: set[str] = set()
    uniq: list[tuple[int, MethodDecl]] = []
    for d, m in fits:
        if m.node_id not in seen:
            seen.add(m.node_id)
            uniq.append((d, m))
    # C# excludes `override` methods from the candidate set: the virtual they override
    # represents them, and a derived class that merely overrides some overloads does not
    # hide the base class's other (possibly better) ones.
    overrides = [(d, m) for d, m in uniq if m.data.is_override]
    declared = [(d, m) for d, m in uniq if not m.data.is_override] or uniq
    scores: dict[str, int] = {}
    if len(declared) > 1 and call.args:
        kept = _filter_by_args(declared, call, ctx, skip_first_param)
        if kept is not None:
            declared, scores = kept
    best = min(d for d, _ in declared)
    nearest = [(d, m) for d, m in declared if d == best]
    if len(nearest) > 1 and scores:
        top = max(scores.get(m.node_id, 0) for _, m in nearest)
        nearest = [(d, m) for d, m in nearest if scores.get(m.node_id, 0) == top]
    winners = [m for _, m in nearest]
    if overrides:
        winners = [_most_derived_override(m, overrides) for m in winners]
    return _dedupe(winners)


def _signature(m: MethodDecl) -> tuple[str, ...]:
    return tuple(p.type_text.replace(" ", "") for p in m.data.params)


def _most_derived_override(m: MethodDecl, overrides: list[tuple[int, MethodDecl]]) -> MethodDecl:
    """The nearest override of `m` visible from the receiver (same name and signature),
    which is what the compiler binds when the receiver's type overrides it."""
    sig = _signature(m)
    generic_base = bool(m.owner.data.own_type_params) or bool(m.data.generic_names)
    matching = [
        (d, o)
        for d, o in overrides
        if o.name == m.name
        and (_signature(o) == sig or (generic_base and len(o.data.params) == len(m.data.params)))
    ]
    return min(matching, key=lambda t: t[0])[1] if matching else m


def _filter_by_args(
    cands: list[tuple[int, MethodDecl]], call: CsCall, ctx: _Ctx, skip_first_param: bool
) -> tuple[list[tuple[int, MethodDecl]], dict[str, int]] | None:
    """Drop candidates whose parameters evidently cannot take the arguments. None
    when nothing is known or every candidate would be dropped (never over-filter)."""
    arg_types = [type_of(a, ctx, 3) for a in call.args or ()]
    if all(t is None for t in arg_types):
        return None
    kept: list[tuple[int, MethodDecl]] = []
    scores: dict[str, int] = {}
    for d, m in cands:
        params = m.data.params[1:] if skip_first_param else m.data.params
        scope = ctx.index.method_scope(m.owner, m.data)
        total, ok = 0, True
        for i, (at, aexpr) in enumerate(zip(arg_types, call.args or (), strict=False)):
            if at is None:
                continue
            if i < len(params):
                p = params[i]
            elif params and params[-1].is_params:
                p = params[-1]
            else:
                break
            ptext = p.type_text
            if p.is_params and i >= len(params) - 1 and ptext.endswith("[]"):
                ptext = ptext[:-2]
            pt = ctx.index.resolve_type(ptext, scope, m.owner.rel_path)
            good, score = _compat(at, pt, aexpr, ctx)
            if not good:
                ok = False
                break
            total += score
        if ok:
            kept.append((d, m))
            scores[m.node_id] = total
    if not kept:
        return None
    return kept, scores


def _internal(methods: list[MethodDecl], *, ambiguous: bool | None = None) -> Resolved:
    ids = [m.node_id for m in methods]
    return Resolved("internal", ids, ambiguous=len(ids) > 1 if ambiguous is None else ambiguous)


def _dedupe(methods: list[MethodDecl]) -> list[MethodDecl]:
    seen: set[str] = set()
    out = []
    for m in methods:
        if m.node_id not in seen:
            seen.add(m.node_id)
            out.append(m)
    return out


def _applicable_extensions(
    call: CsCall, recv: TRef | None, ctx: _Ctx
) -> tuple[list[MethodDecl], bool]:
    """Repo-declared extension methods that could be the target, and whether the
    match is uncertain (receiver type unrelated by name / unknown)."""
    index = ctx.index
    if recv is not None and recv.static_ref:
        return [], False
    pool = index.extensions.get(call.name)
    if not pool:
        return [], False
    found = [(0, m) for m in pool if _arity_ok(m.data, call.arity, as_extension=True)]
    if not found:
        return [], False
    hier_names: set[str] = set()
    if recv is not None:
        hier_names.add(recv.name)
        if recv.internal:
            hier, _ = index.hierarchy(recv.decls)
            for _, d in hier:
                hier_names.add(d.name)
                for b in d.data.bases:
                    hier_names.add(parse_type(b).name.rpartition(".")[2])
    ok_names: frozenset[str] = frozenset()
    if recv is not None and not recv.internal:
        key = "Array" if recv.array_of is not None else recv.name
        ok_names = _ASSIGNABLE.get(key, frozenset())
    keep: list[tuple[int, MethodDecl]] = []
    uncertain = False
    for d, m in found:
        this_name = parse_type(m.data.params[0].type_text).name.rpartition(".")[2]
        generic = this_name in m.data.type_params or this_name in _OBJECT_LIKE
        if recv is None:
            keep.append((d, m))
            uncertain = True
        elif recv.internal:
            if generic or this_name in hier_names:
                keep.append((d, m))
        else:  # a library receiver: a repo extension on a library type
            if this_name in hier_names or generic:
                keep.append((d, m))
            elif index.by_simple_any.get(this_name):
                continue  # extends one of *our* types; a library receiver cannot be it
            elif this_name in ok_names:
                keep.append((d, m))
            elif ok_names and (this_name in _COLLECTION_LIKE or this_name in _DICT_LIKE):
                continue  # a well-known collection type this receiver is not assignable to
            else:
                keep.append((d, m))
                uncertain = True
    if not keep:
        return [], False
    cands = _select(keep, call, ctx, skip_first_param=True)
    return _dedupe(cands), uncertain


def _external_name(recv: TRef | None, name: str) -> str:
    return f"{recv.name}.{name}" if recv is not None else name


_ELEMENT_LAMBDA_METHODS = frozenset(
    {
        "Select", "SelectMany", "Where", "Any", "All", "First", "FirstOrDefault", "Single",
        "SingleOrDefault", "Last", "LastOrDefault", "Count", "LongCount", "Sum", "Min", "Max",
        "Average", "OrderBy", "OrderByDescending", "ThenBy", "ThenByDescending", "GroupBy",
        "TakeWhile", "SkipWhile", "Find", "FindAll", "FindIndex", "FindLast", "Exists", "ForEach",
        "RemoveAll", "ToDictionary", "ToLookup", "Contains", "Aggregate", "SumAsync", "AnyAsync",
        "FirstOrDefaultAsync", "FirstAsync", "SingleOrDefaultAsync", "CountAsync",
        "ToDictionaryAsync",
    }
)  # fmt: skip
"""Library methods whose first lambda parameter is an element of the receiver."""
_LINQ_SAME_ELEMENTS = frozenset(
    {
        "Where", "OrderBy", "OrderByDescending", "ThenBy", "ThenByDescending", "Take", "Skip",
        "TakeWhile", "SkipWhile", "Reverse", "Distinct", "Concat", "Union", "Except",
        "Intersect", "AsEnumerable", "AsQueryable", "Append", "Prepend", "DefaultIfEmpty",
    }
)  # fmt: skip
_LINQ_ONE_ELEMENT = frozenset(
    {
        "First", "FirstOrDefault", "Single", "SingleOrDefault", "Last", "LastOrDefault",
        "ElementAt", "ElementAtOrDefault",
    }
)  # fmt: skip


def _linq_result(expr: CsExpr, ctx: _Ctx, depth: int) -> TRef | None:
    """The type of a LINQ-style call on a library collection whose element type is known,
    so a chain like `order.Lines.Where(...).First().Price()` keeps its element type."""
    name = expr.name
    if not (
        name in _LINQ_SAME_ELEMENTS
        or name in _LINQ_ONE_ELEMENT
        or name in ("ToList", "ToArray", "ToHashSet")
    ):
        return None
    elem = _element_of(type_of(expr.inner, ctx, depth + 1))
    if elem is None:
        return None
    if name in _LINQ_ONE_ELEMENT:
        return elem
    if name == "ToList":
        return TRef(name="List", args=(elem,))
    if name == "ToArray":
        return TRef(name=f"{elem.name}[]", array_of=elem)
    if name == "ToHashSet":
        return TRef(name="HashSet", args=(elem,))
    return TRef(name="IEnumerable", args=(elem,))


def _return_type(expr: CsExpr, ctx: _Ctx, depth: int) -> TRef | None:
    call = CsCall(
        receiver=expr.inner,
        name=expr.name,
        arity=expr.arity,
        lineno=0,
        type_args=expr.type_args,
        args=None,
    )
    res, methods = _resolve_methods(call, ctx, depth + 1)
    if res.kind == "external" and expr.name == "ConfigureAwait" and expr.inner is not None:
        return type_of(expr.inner, ctx, depth + 1)  # Task.ConfigureAwait returns the same task type
    if res.kind in ("external", "unresolved") and expr.inner is not None:
        return _linq_result(expr, ctx, depth)
    if res.kind != "internal" or not methods:
        return None
    texts = {m.data.return_type for m in methods}
    if len(texts) != 1:
        # Overloads that differ in generic detail but agree on the outer type
        # (`IEnumerable<T>` vs `IEnumerable<dynamic>`) still type the next call.
        outer = {parse_type(t or "").name for t in texts}
        if len(outer) != 1 or "" in outer:
            return None
        m = methods[0]
        base = ctx.index.resolve_type(
            parse_type(m.data.return_type or "").name,
            ctx.index.method_scope(m.owner, m.data),
            m.owner.rel_path,
        )
        return TRef(name=base.name, decls=base.decls) if base is not None else None
    m = methods[0]
    rt = m.data.return_type
    if not rt or rt == "void":
        return None
    scope = ctx.index.method_scope(m.owner, m.data)
    subst: dict[str, TRef | None] = {}
    gen = m.data.generic_names
    if expr.type_args and len(gen) == len(expr.type_args):
        subst = {n: ctx.resolve(t) for n, t in zip(gen, expr.type_args, strict=True)}
    return ctx.index.resolve_type_subst(rt, scope, m.owner.rel_path, subst)


def _resolve_methods(call: CsCall, ctx: _Ctx, depth: int = 0) -> tuple[Resolved, list[MethodDecl]]:
    """Attribute a `call`-kind call. Returns the verdict and the internal
    candidates (for return-type inference)."""
    index = ctx.index
    name = call.name
    if call.receiver is None:
        md = ctx.md
        if md is not None and (name in md.local_functions or name in md.locals):
            return _SKIP, []
        owner = ctx.owner
        external_base = False
        while owner is not None:
            found, ext = index.methods_named(index.group_of(owner), name)
            external_base = external_base or ext
            cands = _select(found, call, ctx)
            if cands:
                return _internal(cands), cands
            owner = owner.outer
        for u in ctx.scope.usings:
            if u.kind != "static":
                continue
            groups = index.by_qual.get(u.target)
            if groups:
                cands = _select(index.methods_named(index.group_of(groups[0]), name)[0], call, ctx)
                if cands:
                    return _internal(cands), cands
            else:
                return Resolved("external", [], display=f"{u.target.rpartition('.')[2]}.{name}"), []
        if external_base and ctx.owner is not None:
            return Resolved("external", [], display=f"{ctx.owner.name}.{name}"), []
        if ctx.owner is not None and _library_has_instance("Object", name):
            return Resolved("external", [], display=f"object.{name}"), []
        return Resolved("unresolved", [], display=name), []

    recv_expr = call.receiver
    rt = type_of(recv_expr, ctx, depth)
    if rt is not None and rt.internal:
        found, external_base = index.methods_named(rt.decls, name)
        cands = _select(found, call, ctx)
        if cands:
            return _internal(cands), cands
        if external_base and any(
            _library_has_instance(b, name) for b in index.external_base_names(rt.decls)
        ):
            # Inherited from a library base class: an instance method, so it beats any
            # extension method of the same name.
            return Resolved("external", [], display=_external_name(rt, name)), []
        exts, uncertain = _applicable_extensions(call, rt, ctx)
        if exts:
            return _internal(exts, ambiguous=uncertain or len(exts) > 1), exts
        if external_base or rt.decls[0].data.kind in ("interface", "enum", "struct"):
            return Resolved("external", [], display=_external_name(rt, name)), []
        return Resolved("unresolved", [], display=name), []
    if rt is not None:
        if _library_has_instance(rt.name, name):
            return Resolved("external", [], display=_external_name(rt, name)), []
        exts, uncertain = _applicable_extensions(call, rt, ctx)
        if exts:
            return _internal(exts, ambiguous=uncertain or len(exts) > 1), exts
        return Resolved("external", [], display=_external_name(rt, name)), []
    dotted = _pure_dotted(recv_expr)
    if dotted is not None and dotted[:1].isupper():
        # An unknown capitalised name is far more likely a library *type* (`XElement.Parse`)
        # than a value an extension method applies to.
        return Resolved("unresolved", [], display=name), []
    exts, _ = _applicable_extensions(call, None, ctx)
    if exts and len(exts) <= 3:
        return Resolved("internal", [m.node_id for m in exts], ambiguous=True), exts
    return Resolved("unresolved", [], display=name), []


def _primary_decl(decls: tuple[TypeDecl, ...]) -> TypeDecl:
    """The declaration of a (possibly partial) type that best stands for it: the
    longest one, then the lexicographically first, so the choice is deterministic."""
    return max(
        decls, key=lambda d: (d.raw.end_lineno - d.raw.lineno, [-ord(c) for c in d.rel_path])
    )


def resolve_call(call: CsCall, ctx: _Ctx) -> Resolved:
    index = ctx.index
    if call.kind == "call":
        return _resolve_methods(call, ctx)[0]
    if call.kind == "new":
        ref = ctx.resolve(call.type_text)
        if ref is None:
            return Resolved("unresolved", [], display=parse_type(call.type_text).name or "new")
        if not ref.internal:
            return Resolved("external", [], display=ref.name)
        found, _ = index.methods_named(ref.decls, ref.name)
        ctors = [
            (d, m) for d, m in found if m.data.kind == "ctor" and m.owner.key == ref.decls[0].key
        ]
        cands = _select(ctors, call, ctx)
        if cands:
            return _internal(cands)
        return Resolved("internal", [_primary_decl(ref.decls).class_id])
    if call.kind == "init":
        owner = ctx.owner
        if owner is None:
            return _SKIP
        if call.name == "this":
            found, _ = index.methods_named(index.group_of(owner), owner.name)
            cands = _select([(d, m) for d, m in found if m.data.kind == "ctor"], call, ctx)
            return _internal(cands) if cands else _SKIP
        for base_text in owner.data.bases:
            ref = index.resolve_type(base_text, owner.base_scope, owner.rel_path)
            if ref is not None and ref.internal and ref.decls[0].data.kind != "interface":
                found, _ = index.methods_named(ref.decls, ref.name)
                ctors = [
                    (d, m)
                    for d, m in found
                    if m.data.kind == "ctor" and m.owner.key == ref.decls[0].key
                ]
                cands = _select(ctors, call, ctx)
                return (
                    _internal(cands)
                    if cands
                    else Resolved("internal", [_primary_decl(ref.decls).class_id])
                )
            if ref is not None and not ref.internal and not _looks_like_interface(ref.name):
                return Resolved("external", [], display=ref.name)
        return _SKIP
    return _SKIP


