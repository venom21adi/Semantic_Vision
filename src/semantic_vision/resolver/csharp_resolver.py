def _edges_for(source: str, call: CsCall, ctx: _Ctx, rel_path: str, out: dict[tuple, Edge]) -> None:
    res = resolve_call(call, ctx)
    if res.kind == "skip":
        return
    if res.kind == "internal":
        ambiguous = res.ambiguous
        targets = res.targets
        if len(targets) > MAX_AMBIGUOUS_TARGETS:
            key = (source, f"unresolved::{call.name}", False, True)
            out.setdefault(
                key,
                Edge(
                    source=source,
                    target=f"unresolved::{call.name}",
                    kind=EdgeKind.CALLS,
                    ambiguous=True,
                ),
            )
            return
        for t in targets:
            out.setdefault(
                (source, t, False, ambiguous),
                Edge(source=source, target=t, kind=EdgeKind.CALLS, ambiguous=ambiguous),
            )
    elif res.kind == "external":
        target = f"external::{res.display}"
        out.setdefault(
            (source, target, True, False),
            Edge(source=source, target=target, kind=EdgeKind.CALLS, external=True),
        )
    else:
        target = f"unresolved::{res.display}"
        out.setdefault(
            (source, target, False, True),
            Edge(source=source, target=target, kind=EdgeKind.CALLS, ambiguous=True),
        )


def resolve_module_calls(index: CsIndex, rel_path: str, raw: RawModule) -> list[Edge]:
    out: dict[tuple, Edge] = {}

    def do_class(cls: RawClass, class_id: str) -> None:
        decl = index.decl_by_class_id.get(class_id)
        data: CsClassData | None = cls.lang_data
        if decl is None or data is None:
            return
        ctx = _Ctx(index, decl, data.init_data, rel_path)
        for call in data.init_data.calls:
            _edges_for(class_id, call, ctx, rel_path, out)
        for fn in cls.methods:
            md: CsMethodData | None = fn.lang_data
            if md is None or not md.calls:
                continue
            fctx = _Ctx(index, decl, md, rel_path)
            fid = method_node_id(class_id, fn)
            for call in md.calls:
                _edges_for(fid, call, fctx, rel_path, out)
        for nested in cls.nested_classes:
            do_class(nested, f"{class_id}.{nested.name}")

    for cls in raw.classes:
        do_class(cls, f"{rel_path}::{cls.name}")
    mdata: CsModuleData | None = raw.lang_data
    if mdata is not None and mdata.top_level is not None and mdata.top_level.calls:
        ctx = _Ctx(index, None, mdata.top_level, rel_path)
        # Top-level statements see the file's `using`s.
        file_usings = tuple(
            CsUsing(
                kind="static" if i.level == 1 else ("alias" if i.asname else "namespace"),
                target=f"{i.module}.{i.name}" if i.module else i.name,
                alias=i.asname,
            )
            for i in raw.imports
        )
        ctx.scope = Scope(None, "", file_usings, frozenset())
        for call in mdata.top_level.calls:
            _edges_for(rel_path, call, ctx, rel_path, out)
    return list(out.values())


def mark_dispatch_targets(index: CsIndex) -> None:
    """Methods that implement an interface member or override a base member are
    reached through virtual dispatch the call graph does not model (callers point
    at the interface/base method). Flag them like framework-invoked methods so
    dead-code analysis does not report them."""
    for decl in index.decl_by_class_id.values():
        if decl.data.kind == "interface" or not decl.data.bases:
            continue
        hier, _ = index.hierarchy(index.group_of(decl))
        inherited: dict[str, list[MethodDecl]] = defaultdict(list)
        for depth, d in hier:
            if depth == 0:
                continue
            for name, ms in d.methods.items():
                inherited[name].extend(ms)
        if not inherited:
            continue
        for fn in decl.raw.methods:
            md: CsMethodData | None = fn.lang_data
            if md is None or fn.has_decorators or md.kind != "method":
                continue
            if any(_arity_ok(o.data, len(md.params)) for o in inherited.get(fn.name, ())):
                fn.has_decorators = True


