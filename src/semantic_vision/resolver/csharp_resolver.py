def resolve_imports(
    index: CsIndex, rel_path: str, raw: RawModule, modules: dict[str, ModuleIndex]
) -> ImportResolution:
    edges: dict[tuple, Edge] = {}
    for imp in raw.imports:
        target = f"{imp.module}.{imp.name}" if imp.module else imp.name
        if imp.level == 1:  # using static Type
            groups = index.by_qual.get(target)
            if groups:
                edges.setdefault(
                    (groups[0].rel_path, False),
                    Edge(source=rel_path, target=groups[0].rel_path, kind=EdgeKind.IMPORTS),
                )
            else:
                edges.setdefault(
                    (f"external::{target}", True),
                    Edge(
                        source=rel_path,
                        target=f"external::{target}",
                        kind=EdgeKind.IMPORTS,
                        external=True,
                    ),
                )
            continue
        files = index.ns_files.get(target)
        if target in index.namespaces and files:
            directory = index.namespace_directory(target, rel_path)
            if directory:
                edges.setdefault(
                    (directory, False),
                    Edge(source=rel_path, target=directory, kind=EdgeKind.IMPORTS, ambiguous=True),
                )
        elif target in index.by_qual:  # alias to a type
            edges.setdefault(
                (index.by_qual[target][0].rel_path, False),
                Edge(
                    source=rel_path, target=index.by_qual[target][0].rel_path, kind=EdgeKind.IMPORTS
                ),
            )
        else:
            edges.setdefault(
                (f"external::{target}", True),
                Edge(
                    source=rel_path,
                    target=f"external::{target}",
                    kind=EdgeKind.IMPORTS,
                    external=True,
                ),
            )
    bindings: dict[str, ImportBinding] = {}
    return ImportResolution(bindings=bindings, edges=list(edges.values()))
